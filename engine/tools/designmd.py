#!/usr/bin/env python3
"""Export the project's design system as DESIGN.md, in the nine-section format design agents read
(Claude Design, Google Stitch and others; the section list follows VoltAgent's awesome-claude-design, MIT).

    designmd.py [--out <file>]      default out/design/DESIGN.md; checkpoint.py also puts it in out/package/

Built from data only: tokens.json, structure.json, interaction.json, fingerprints/chosen.json, rationale.md and
brief.json. Run after G7 (S7) and again at packaging; edit the data, never the file. Holds the project's own values,
so it lives in the project, never in the engine.
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kitlib import J, P, current_project, event, read_json, write_atomic
import policy


def lum(h):
    h = h.lstrip('#'); h = ''.join(c * 2 for c in h) if len(h) == 3 else h[:6]
    c = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def ratio(a, b):
    try:
        la, lb = sorted((lum(a), lum(b)), reverse=True)
        return f'{(la + 0.05) / (lb + 0.05):.1f}:1'
    except (ValueError, IndexError):
        return 'n/a'


def first_words(text, n):
    w = re.sub(r'\s+', ' ', re.sub(r'^#.*$', '', text or '', flags=re.M)).strip().split(' ')
    return ' '.join(w[:n]) + (' ...' if len(w) > n else '')


def build(brief):
    tok, stc = read_json(P('tokens.json'), {}), read_json(P('structure.json'), {})
    fp, inter = read_json(P('fingerprints', 'chosen.json'), {}), read_json(P('interaction.json'), [])
    defaults = read_json(J('ref', 'defaults.json'), {})
    name = brief.get('site_name') or current_project()
    col, ty = tok.get('color') or {}, tok.get('type') or {}
    paper, ink = col.get('paper') or col.get('ground') or '#ffffff', col.get('ink') or '#000000'
    rat = open(P('rationale.md'), encoding='utf-8').read() if os.path.exists(P('rationale.md')) else ''
    L = [f'# {name}: DESIGN.md', '',
         f'Generated by the design kit (tools/designmd.py) from the project data. WCAG target {str(brief.get("wcag", "AAA")).upper()}; '
         f'language {brief.get("lang", "en")} ({policy.text_dir(brief)}).', '',
         '## 1. Visual theme and atmosphere', '']
    for k, label in (('form', 'Page form'), ('movement', 'Design movement'), ('image', 'Image treatment'), ('texture', 'Texture'), ('motion', 'Motion')):
        if fp.get(k):
            L.append(f'- {label}: {fp[k]}')
    if fp.get('moves'):
        L.append('- Signature moves: ' + '; '.join(m for m in fp['moves'] if m))
    if rat:
        L += ['', first_words(rat, 80)]
    L += ['', '## 2. Colour palette and roles', '', '| Role | Value | On paper | On ink |', '|---|---|---|---|']
    L += [f'| {k} | {v} | {ratio(v, paper)} | {ratio(v, ink)} |' for k, v in col.items()]
    L += ['', 'Text pairs meet 7:1 (4.5:1 for large text) at AAA, 4.5:1 (3:1) at AA. Colours appear in CSS only as `var(--c-<role>)`.',
          '', '## 3. Typography rules', '', '| Face | Role | Source | Licence | Fallback |', '|---|---|---|---|---|']
    L += [f'| {f.get("family")} | {f.get("role", "")} | {f.get("source", "")} | {f.get("licence", "")} | {f.get("alternate", "")} |' for f in ty.get('faces', [])]
    if ty.get('scale'):
        L += ['', 'Scale: ' + ', '.join(str(x) for x in ty['scale']) + ' (CSS `--t-1` upward).']
    for el, r in (ty.get('roles') or {}).items():
        L.append(f'- {el}: ' + ', '.join(f'{k} {v}' for k, v in r.items()))
    L += ['- Body flush left, under 80 characters a line, never justified; no widows; one numeral style.', '',
          '## 4. Component stylings', '']
    rows = inter if isinstance(inter, list) else []
    if rows:
        L += ['| Component | States | Keyboard | Motion | Reduced motion |', '|---|---|---|---|---|']
        L += [f'| {r.get("component")} | {", ".join(r.get("states", []))} | {r.get("keyboard", "")} | {r.get("motion", "")} | {r.get("reduced_motion", "")} |' for r in rows]
    else:
        L.append('No interaction.json yet (S7 writes it).')
    parts = sorted(os.path.basename(f)[:-5] for f in os.listdir(P('partials')) if f.endswith('.html')) if os.path.isdir(P('partials')) else []
    if parts:
        L += ['', 'Partials (each with its own class prefix): ' + ', '.join(parts) + '.']
    st = tok.get('states') or {}
    if st:
        L.append('State tokens: ' + '; '.join(f'{k} ' + ', '.join(f'{a} {b}' for a, b in (v.items() if isinstance(v, dict) else [('', v)])) for k, v in st.items()) + '.')
    if policy.consent_on(brief):
        L.append('Consent banner: the kit component (reject beside accept, same class), styled only through tokens.')
    g = stc.get('grid') or {}
    L += ['', '## 5. Layout principles', '']
    if stc.get('page_form'):
        L.append(f'- Page form: {stc["page_form"]}')
    if g:
        L.append(f'- Grid: {g.get("columns", "?")} columns, gutter {g.get("gutter", "?")}, margin {g.get("margin", "?")}' + (f', nested {g["nested"]}' if g.get('nested') else ''))
    if tok.get('space'):
        L.append('- Space scale: ' + ', '.join(str(x) for x in tok['space']) + ' (`--s-1` upward); space between groups at least twice the space within.')
    L += ['- Text reads in one sequence: no side-by-side text columns, card grids or sidebars.',
          '- One loud move per screen and a rest after it; at most four shared left edges per desktop screen.', '',
          '## 6. Depth and elevation', '']
    L.append('- Radius: ' + (', '.join(str(x) for x in tok.get('radius', [])) or 'none') + '.')
    L.append('- Shadows: ' + (', '.join(str(x) for x in tok['shadow']) if tok.get('shadow') else 'none; depth comes from colour, rules and overlap of shapes, never of photos.') )
    L += ['- One heavy rule for section dividers, 1px hairlines inside a section, never two rules stacked.', '',
          '## 7. Do and do not', '', '**Do**']
    L += [f'- {m}' for m in (fp.get('moves') or []) if m] + ['- Take every colour, size and space from the tokens.',
                                                              '- Keep motion to transform and opacity, under 300ms for interface feedback, with a reduced-motion fallback.']
    L += ['', '**Do not**'] + [f'- {m}' for m in (defaults.get('moves') or [])[:14]]
    L += [f'- Set {", ".join((defaults.get("faces") or [])[:8])} as the display face (common tool defaults).', '',
          '## 8. Responsive behaviour', '']
    if tok.get('breakpoints'):
        L.append('- Breakpoints: ' + ', '.join(str(x) for x in tok['breakpoints']) + '.')
    L += ['- Checked at 1440, 768, 390 and 320: no sideways scroll, text reflows, copy 30% longer still fits, long words wrap.',
          '- Targets at least 44px; tap-to-call phone numbers; full keyboard access with a visible focus ring.', '',
          '## 9. Agent prompt guide', '',
          f'You are extending the {name} site. Write data, not pages: text in pages/<page>.json, styles in tokens.json and partials/<name>.css '
          'with the partial\'s own class prefix and colours only as var(--c-<role>). Rebuild with tools/build.py --all, then run tools/pass.py --all '
          'and tools/comply.py; fix only what they flag. Keep the signature moves above, keep the page form, and add no new face, colour or motion '
          'without the creative director. Plain language at the brief\'s reading level; no invented facts.', '']
    return '\n'.join(L)


def main(a):
    if a and a[0] in ('-h', '--help'):
        print(__doc__); return 0
    current_project(); event('call')
    out = a[a.index('--out') + 1] if '--out' in a else P('out', 'design', 'DESIGN.md')
    write_atomic(out, build(read_json(P('brief.json'), {})))
    print(f'designmd: {os.path.relpath(out, P())} (nine sections from tokens, structure, interaction, fingerprint)')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
