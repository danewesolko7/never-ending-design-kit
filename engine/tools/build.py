# ---------- tokens to CSS ----------
def flat(prefix, v, out):
    if isinstance(v, dict):
        for k, x in v.items():
            flat(f'{prefix}-{k}', x, out)
    elif isinstance(v, list):
        for i, x in enumerate(v):
            flat(f'{prefix}-{i + 1}', x, out)
    else:
        out.append((prefix, v))


def px(v):
    return f'{v}px' if isinstance(v, (int, float)) else str(v)


def font_file(name):
    for base in [P('fonts')] + glob.glob(os.path.join(node_env()['KIT_NODE'], '@fontsource*', '*', 'files')) \
            + glob.glob(J('tools', 'node_modules', '@fontsource*', '*', 'files')):
        f = os.path.join(base, name)
        if os.path.exists(f):
            return f
    return None


def tokens_css(tok, site):
    root, fonts = [], []
    for k, v in (tok.get('color') or {}).items():
        root.append(f'--c-{k}:{v}')
    ty = tok.get('type') or {}
    faces = ty.get('faces') or []
    for i, f in enumerate(faces):
        fam = f['family']
        gen = f.get('generic', 'sans-serif')
        alt = f.get('alternate')
        root.append(f"--f-{i + 1}:'{fam}'" + (f",'{alt}'" if alt else '') + f',{gen}')
        if f.get('role'):
            root.append(f"--f-{f['role']}:var(--f-{i + 1})")
        for ff in f.get('files') or []:
            src = font_file(ff['file'])
            if not src:
                err(f'font file {ff["file"]} for {fam} not found (run setup.sh, or the CD supplies it in projects/<p>/fonts/)')
                continue
            os.makedirs(os.path.join(site, 'fonts'), exist_ok=True)
            shutil.copy(src, os.path.join(site, 'fonts', ff['file']))
            fonts.append("@font-face{font-family:'%s';src:url(fonts/%s) format('woff2');font-weight:%s;font-style:%s;font-display:swap}"
                         % (fam, ff['file'], ff.get('weight', '100 900'), ff.get('style', 'normal')))
    for i, s in enumerate(ty.get('scale') or []):
        root.append(f'--t-{i + 1}:{px(s)}')
    for name in ('space', 'radius'):
        for i, s in enumerate(tok.get(name) or []):
            root.append(f'--{name[0]}-{i + 1}:{px(s)}')
    out = []
    flat('state', tok.get('states') or {}, out)
    mo = tok.get('motion') or {}
    for i, d in enumerate(mo.get('durations') or []):
        root.append(f'--dur-{i + 1}:{d}ms' if isinstance(d, (int, float)) else f'--dur-{i + 1}:{d}')
    if mo.get('easing'):
        root.append(f'--ease:{mo["easing"]}')
    for k, v in out:
        if isinstance(v, (str, int, float)):
            root.append(f'--{k}:{v}')
    roles = []
    for el, r in (ty.get('roles') or {}).items():
        sel = {'body': '.k-body', 'lede': '.k-lede', 'kicker': '.k-kicker', 'caption': '.k-caption'}.get(el, el)
        decl = []
        if r.get('face'):
            decl.append(f'font-family:var(--f-{r["face"]})' if isinstance(r['face'], int) or str(r['face']).isdigit() else f'font-family:var(--f-{r["face"]})')
        for k, prop in (('size', 'font-size'), ('weight', 'font-weight'), ('line', 'line-height'), ('tracking', 'letter-spacing'), ('stretch', 'font-stretch')):
            if r.get(k) is not None:
                decl.append(f'{prop}:{px(r[k]) if k == "size" else r[k]}')
        if decl:
            roles.append(f'{sel}{{{";".join(decl)}}}')
    return fonts, ':root{' + ';'.join(root) + '}', roles


